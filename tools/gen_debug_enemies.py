#!/usr/bin/env python3
"""native/platform/debug_enemies.h (Esc > Debug > Enemy) from tools/data/enemy_packs.txt: each enemy
profile with the areas whose packs hold its model. Left out: the profiles in
tools/data/enemy_skip.txt ("name reason"), which crashed when spawned in a test, and those no
single area loads."""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
skip = set()
for line in open(os.path.join(root, "tools/data/enemy_skip.txt")):
    if line.strip() and not line.startswith("#"):
        skip.add(line.split()[0])
rows = []
for line in open(os.path.join(root, "tools/data/enemy_packs.txt")):
    p = line.split()
    areas = [a for a in p[2:] if a == "ActorCommon" or re.fullmatch(r"(Field|Indoor|Cave|Dungeon|Attraction|CrossBattle)[A-Za-z]*\d+", a)]
    if p and p[0].startswith("Enemy") and p[0] not in skip and areas:
        rows.append('    {"%s", " %s "},' % (p[0], " ".join(areas)))
with open(os.path.join(root, "native/platform/debug_enemies.h"), "w") as f:
    f.write("/* generated by tools/gen_debug_enemies.py: do not edit */\n")
    f.write("static const struct { const char *name, *areas; } dbg_enemies[] = {\n")
    f.write("\n".join(rows) + "\n};\n")
print("debug_enemies.h: %d enemies" % len(rows))
